# Range of Index 
# Syntax = listName[start : end : jumpIndex]

animals = ["cat", "dog", "bat", "mouse", "pig", "cow", "horse", "donkey", "goat"]
print(animals[3:7])
print(animals[-7:-2])
print(" ")

print(animals[4:])
print(animals[-4:])
print(" ")

print(animals[:5])
print(animals[:-2])
print(" ")

print(animals[::2])
print(animals[-8:-1:2])
print(animals[1:8:3])